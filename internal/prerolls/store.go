const prerollCols = `seq,id,name,enabled,rules_json,frequency_json,priority,play_order,video_state,video_problem,video_source,source_path,duration_ms,width,height,bitrate_kbps,size_bytes,created_at,updated_at`

type scanner interface{ Scan(...any) error }

func scanPreroll(row scanner) (Preroll, error) {
	var p Preroll
	var enabled int
	var rules, freq string
	var created, updated int64
	if err := row.Scan(&p.seq, &p.ID, &p.Name, &enabled, &rules, &freq, &p.Priority, &p.Order,
		&p.Video.State, &p.Video.Problem, &p.Video.Source, &p.sourcePath, &p.Video.DurationMs,
		&p.Video.Width, &p.Video.Height, &p.bitrate, &p.sizeBytes, &created, &updated); err != nil {
		return Preroll{}, err
	}
	p.Enabled = enabled != 0
	_ = json.Unmarshal([]byte(rules), &p.Rules)
	_ = json.Unmarshal([]byte(freq), &p.Frequency)
	in := Input{Name: p.Name, Rules: p.Rules, Frequency: p.Frequency, Priority: p.Priority, Order: p.Order}
	if normalize(&in) == nil {
		p.Rules, p.Frequency, p.Order = in.Rules, in.Frequency, in.Order
	}
	p.CreatedAt = time.Unix(0, created).UTC()
	p.UpdatedAt = time.Unix(0, updated).UTC()
	// Browser paths, like collection artwork; the stamp changes with
	// every new video.
	stamp := "?v=" + strconv.FormatInt(updated, 36)
	p.Video.ThumbURL = "/ether/api/admin/prerolls/" + p.ID + "/thumb" + stamp
	p.Video.PreviewURL = "/ether/api/admin/prerolls/" + p.ID + "/preview" + stamp
	return p, nil
}

func newPublicID() string {
	var b [10]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err)
	}
	return "pr_" + strings.ToLower(base32.StdEncoding.WithPadding(base32.NoPadding).EncodeToString(b[:]))
}

func (s *Service) loadAll(ctx context.Context) ([]Preroll, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT `+prerollCols+` FROM prerolls ORDER BY priority DESC, seq`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Preroll
	for rows.Next() {
		p, err := scanPreroll(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, p)
	}
	return out, rows.Err()
}

func (s *Service) byID(ctx context.Context, id string) (Preroll, error) {
	p, err := scanPreroll(s.db.QueryRowContext(ctx, `SELECT `+prerollCols+` FROM prerolls WHERE id=?`, id))
	if errors.Is(err, sql.ErrNoRows) {
		return Preroll{}, ErrNotFound
	}
	return p, err
}

func (s *Service) bySeq(ctx context.Context, seq int64) (Preroll, error) {
	p, err := scanPreroll(s.db.QueryRowContext(ctx, `SELECT `+prerollCols+` FROM prerolls WHERE seq=?`, seq))
	if errors.Is(err, sql.ErrNoRows) {
		return Preroll{}, ErrNotFound
	}
	return p, err
}

func (s *Service) setting(ctx context.Context, k string) string {
	var v string
	_ = s.db.QueryRowContext(ctx, `SELECT v FROM prerolls_settings WHERE k=?`, k).Scan(&v)
	return v
}

func (s *Service) putSetting(ctx context.Context, k, v string) error {
	_, err := s.db.ExecContext(ctx, `INSERT INTO prerolls_settings(k,v) VALUES(?,?) ON CONFLICT(k) DO UPDATE SET v=excluded.v`, k, v)
	return err
}

type videoUpdate struct {
	state, problem, source, sourcePath string
	durationMs                         int64
	width, height, bitrate             int
	size                               int64
}

func (s *Service) setVideo(ctx context.Context, seq int64, v videoUpdate) error {
	_, err := s.db.ExecContext(ctx, `UPDATE prerolls SET video_state=?,video_problem=?,video_source=?,source_path=?,
		duration_ms=?,width=?,height=?,bitrate_kbps=?,size_bytes=?,updated_at=? WHERE seq=?`,
		v.state, v.problem, v.source, v.sourcePath, v.durationMs, v.width, v.height, v.bitrate, v.size, s.now().UnixNano(), seq)
	s.invalidate()
	return err
}

// plays30d counts each pre-roll's plays in the stats window.
func (s *Service) plays30d(ctx context.Context) (map[int64]int, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT preroll_seq, COUNT(*) FROM prerolls_plays WHERE at>=? GROUP BY preroll_seq`, s.now().Add(-statsWindow).UnixNano())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := map[int64]int{}
	for rows.Next() {
		var seq int64
		var n int
		if err := rows.Scan(&seq, &n); err != nil {
			return nil, err
		}
		out[seq] = n
	}
	return out, rows.Err()
}

// viewerPlay is one row of a viewer's recent pre-roll plays.
type viewerPlay struct {
	seq int64
	key int64
	at  time.Time
}

// recentPlays returns a viewer's plays since since, newest first, bounded.
func (s *Service) recentPlays(ctx context.Context, viewerID int64, since time.Time) ([]viewerPlay, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT preroll_seq, rating_key, at FROM prerolls_plays
		WHERE viewer_id=? AND at>=? ORDER BY at DESC LIMIT 5000`, viewerID, since.UnixNano())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []viewerPlay
	for rows.Next() {
		var p viewerPlay
		var at int64
		if err := rows.Scan(&p.seq, &p.key, &at); err != nil {
			return nil, err
		}
		p.at = time.Unix(0, at)
		out = append(out, p)
	}
	return out, rows.Err()
}

// titlePlays returns the pre-rolls a viewer already saw before key.
func (s *Service) titlePlays(ctx context.Context, viewerID, key int64) (map[int64]bool, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT DISTINCT preroll_seq FROM prerolls_plays
		WHERE viewer_id=? AND rating_key=? AND at>=?`, viewerID, key, s.now().Add(-MaxRetention).UnixNano())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := map[int64]bool{}
	for rows.Next() {
		var seq int64
		if err := rows.Scan(&seq); err != nil {
			return nil, err
		}
		out[seq] = true
	}
	return out, rows.Err()
}
